void max7219_init(void) {
    // gpio_fsel(MAX7219_CS_PIN, GPIO_OUTPUT);
    gpio_fsel(MAX7219_CS_PIN, GPIO_ALT_0);   // SPI0_CE0_N
    gpio_fsel(MAX7219_MOSI_PIN, GPIO_ALT_0); // SPI0_MOSI
    gpio_fsel(MAX7219_SCLK_PIN, GPIO_ALT_0); // SPI0_SCLK

    spi_cdiv(16);

    // ADCS does successfully make the SPI interface drive the CS pin it seems,
    // CS pins are active-low by default
    spi_ctl_write(SPI_CS_0 | SPI_ADCS);

    max7219_write(0x9, 0x00, 0x9, 0x00); // decode mode = no decode
    max7219_write(0xa, 0x03, 0xa, 0x03); // intensity (duty cycle) = 7/32
    max7219_write(0xb, 0x07, 0xb, 0x07); // scan limit = all digits
    max7219_write(0xc, 0x01, 0xc, 0x01); // shutdown = normal operation
    max7219_write(0xf, 0x00, 0xf, 0x00); // display test = normal operation
}

void max7219_write(uint8_t addr1, uint8_t data1, uint8_t addr2, uint8_t data2) {
    // gpio_write(MAX7219_CS_PIN, GPIO_LOW);

    spi_tx_begin();
    spi_tx_write(addr1);
    spi_tx_write(data1);
    spi_tx_write(addr2);
    spi_tx_write(data2);
    spi_tx_end();

    // gpio_write(MAX7219_CS_PIN, GPIO_HIGH);
}
